import { execOnce } from './sshManager.js';

/**
 * List recent Codex CLI and Antigravity CLI sessions stored on the target host
 * (works over both local and SSH connections).
 */
export async function listRemoteSessions(hostConfig) {
  const pyCode = [
    'import json, os, glob, re',
    'out = []',
    '# ---- 1. Codex sessions ----',
    'idx_titles = {}',
    'idx_path = os.path.expanduser("~/.codex/session_index.jsonl")',
    'if os.path.exists(idx_path):',
    '    for line in open(idx_path, encoding="utf-8", errors="ignore"):',
    '        try:',
    '            o = json.loads(line)',
    '            if o.get("id") and o.get("thread_name"):',
    '                idx_titles[o["id"]] = o["thread_name"]',
    '        except Exception: pass',
    'cfiles = sorted(glob.glob(os.path.expanduser("~/.codex/sessions/**/*.jsonl"), recursive=True), key=os.path.getmtime, reverse=True)',
    'for fp in cfiles[:40]:',
    '    mtime_ms = int(os.path.getmtime(fp) * 1000)',
    '    sid = ""; cwd = "~"; model = ""; first_user = ""; msg_count = 0',
    '    m_id = re.search(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\\.jsonl$", os.path.basename(fp))',
    '    if m_id: sid = m_id.group(1)',
    '    try:',
    '        for line in open(fp, encoding="utf-8", errors="ignore"):',
    '            if "session_meta" in line or "turn_context" in line or "thread_settings_applied" in line or "UserMessage" in line or "AgentMessage" in line:',
    '                try: o = json.loads(line)',
    '                except Exception: continue',
    '                t = o.get("type")',
    '                p = o.get("payload") or {}',
    '                if t == "session_meta" and p.get("session_id"): sid = p["session_id"]',
    '                elif t == "turn_context" and p.get("cwd"): cwd = p["cwd"]',
    '                elif t == "event_msg" and p.get("type") == "thread_settings_applied":',
    '                    ts = p.get("thread_settings") or {}',
    '                    if ts.get("model"): model = ts["model"]',
    '                elif t == "event_msg" and p.get("type") == "item_completed":',
    '                    it = p.get("item") or {}',
    '                    it_type = it.get("type")',
    '                    if it_type == "UserMessage":',
    '                        msg_count += 1',
    '                        if not first_user:',
    '                            parts = [c.get("text", "") for c in (it.get("content") or []) if isinstance(c, dict)]',
    '                            first_user = " ".join(parts).strip()',
    '                    elif it_type == "AgentMessage":',
    '                        msg_count += 1',
    '    except Exception: continue',
    '    if not sid or msg_count == 0: continue',
    '    title = idx_titles.get(sid) or first_user.replace("\\n", " ")[:40] or f"Codex {sid[:8]}"',
    '    out.append({"agent": "codex", "sessionId": sid, "title": title, "cwd": cwd, "model": model, "messageCount": msg_count, "updatedAt": mtime_ms})',
    '# ---- 2. Antigravity CLI sessions ----',
    'agy_meta = {}',
    'meta_path = os.path.expanduser("~/.gemini/antigravity-cli/cache/conversation_metadata.json")',
    'if os.path.exists(meta_path):',
    '    try:',
    '        md = json.load(open(meta_path, encoding="utf-8"))',
    '        agy_meta = md.get("conversations") or {}',
    '    except Exception: pass',
    'afiles = sorted(glob.glob(os.path.expanduser("~/.gemini/antigravity-cli/brain/*/.system_generated/logs/transcript.jsonl")), key=os.path.getmtime, reverse=True)',
    'for fp in afiles[:40]:',
    '    mtime_ms = int(os.path.getmtime(fp) * 1000)',
    '    cid = os.path.basename(os.path.dirname(os.path.dirname(os.path.dirname(fp))))',
    '    meta = (agy_meta.get(cid) or {}).get("summary") or {}',
    '    cwd = "~"',
    '    uris = meta.get("WorkspaceURIs") or []',
    '    if uris and isinstance(uris[0], str):',
    '        cwd = uris[0].replace("file://", "")',
    '    first_user = ""; model = ""; msg_count = 0',
    '    try:',
    '        for line in open(fp, encoding="utf-8", errors="ignore"):',
    '            if "USER_INPUT" not in line and "PLANNER_RESPONSE" not in line: continue',
    '            try: o = json.loads(line)',
    '            except Exception: continue',
    '            if o.get("source") == "USER_EXPLICIT" and o.get("type") == "USER_INPUT":',
    '                msg_count += 1',
    '                if not first_user:',
    '                    raw = o.get("content") or ""',
    '                    m = re.search(r"<USER_REQUEST>\\s*(.*?)\\s*</USER_REQUEST>", raw, re.S)',
    '                    first_user = (m.group(1) if m else raw).strip()',
    '            elif o.get("source") == "MODEL" and o.get("type") == "PLANNER_RESPONSE":',
    '                if o.get("model"): model = o["model"]',
    '                if (o.get("content") or "").strip(): msg_count += 1',
    '    except Exception: continue',
    '    if msg_count == 0: continue',
    '    title = (meta.get("Title") or "").strip() or first_user.replace("\\n", " ")[:40] or (meta.get("Preview") or "")[:40] or f"AGY {cid[:8]}"',
    '    out.append({"agent": "agy", "sessionId": cid, "title": title, "cwd": cwd, "model": model, "messageCount": msg_count, "updatedAt": mtime_ms})',
    'out.sort(key=lambda x: x["updatedAt"], reverse=True)',
    'print(json.dumps(out[:50], ensure_ascii=False))'
  ].join('\n');

  const b64Py = Buffer.from(pyCode, 'utf8').toString('base64');
  const cmd = `python3 -c "$(printf '%s' '${b64Py}' | base64 -d)" 2>/dev/null || echo '[]'`;
  const res = await execOnce(hostConfig, cmd, 15000);
  const parsed = JSON.parse((res.stdout || '').trim() || '[]');
  return Array.isArray(parsed) ? parsed : [];
}

/**
 * Fetch and parse full chat messages for a specific remote Codex or Antigravity session.
 */
export async function fetchRemoteSessionDetail(hostConfig, agent, sessionId) {
  const b64Args = Buffer.from(JSON.stringify({ agent, sessionId }), 'utf8').toString('base64');

  const pyCode = [
    'import json, os, glob, re, sys, base64',
    'from datetime import datetime',
    'args = json.loads(base64.b64decode(sys.argv[1]).decode("utf-8"))',
    'agent = args["agent"]',
    'sid = args["sessionId"]',
    'def parse_ts(s):',
    '    if not s: return 0',
    '    try: return int(datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp() * 1000)',
    '    except Exception: return 0',
    'result = {"agent": agent, "sessionId": sid, "title": "", "cwd": "~", "model": "", "effort": "", "messages": []}',
    'if agent == "codex":',
    '    idx_path = os.path.expanduser("~/.codex/session_index.jsonl")',
    '    if os.path.exists(idx_path):',
    '        for line in open(idx_path, encoding="utf-8", errors="ignore"):',
    '            try:',
    '                o = json.loads(line)',
    '                if o.get("id") == sid and o.get("thread_name"): result["title"] = o["thread_name"]',
    '            except Exception: pass',
    '    matches = glob.glob(os.path.expanduser(f"~/.codex/sessions/**/*{sid}*.jsonl"), recursive=True)',
    '    if not matches:',
    '        print(json.dumps({"error": "未找到对应的 Codex 会话文件"}, ensure_ascii=False))',
    '        sys.exit(0)',
    '    fp = matches[0]',
    '    messages = []',
    '    cur_asst = None',
    '    def flush_asst():',
    '        global cur_asst',
    '        if cur_asst and (cur_asst["content"].strip() or cur_asst["tools"] or cur_asst["thinking"].strip()):',
    '            messages.append(cur_asst)',
    '        cur_asst = None',
    '    for line in open(fp, encoding="utf-8", errors="ignore"):',
    '        try: o = json.loads(line)',
    '        except Exception: continue',
    '        t = o.get("type")',
    '        p = o.get("payload") or {}',
    '        ts = parse_ts(o.get("timestamp"))',
    '        if t == "turn_context" and p.get("cwd"): result["cwd"] = p["cwd"]',
    '        elif t == "event_msg" and p.get("type") == "thread_settings_applied":',
    '            ts_obj = p.get("thread_settings") or {}',
    '            if ts_obj.get("model"): result["model"] = ts_obj["model"]',
    '        elif t == "response_item" and p.get("type") == "configuration_update":',
    '            r = p.get("reasoning") or {}',
    '            if r.get("effort"): result["effort"] = r["effort"]',
    '        elif t == "event_msg" and p.get("type") == "item_completed":',
    '            it = p.get("item") or {}',
    '            it_type = it.get("type")',
    '            if it_type == "UserMessage":',
    '                flush_asst()',
    '                parts = [c.get("text", "") for c in (it.get("content") or []) if isinstance(c, dict) and c.get("text")]',
    '                txt = "\\n".join(parts).strip()',
    '                if txt:',
    '                    messages.append({"id": it.get("id") or f"u_{len(messages)}", "role": "user", "content": txt, "status": "done", "createdAt": ts})',
    '                    if not result["title"]: result["title"] = txt.replace("\\n", " ")[:36]',
    '            elif it_type == "AgentMessage":',
    '                parts = [c.get("text", "") for c in (it.get("content") or []) if isinstance(c, dict) and c.get("text")]',
    '                txt = "\\n".join(parts).strip()',
    '                if txt:',
    '                    if cur_asst is None:',
    '                        cur_asst = {"id": it.get("id") or f"a_{len(messages)}", "role": "assistant", "content": txt, "thinking": "", "tools": [], "status": "done", "createdAt": ts}',
    '                    else:',
    '                        cur_asst["content"] = (cur_asst["content"] + "\\n\\n" + txt).strip() if cur_asst["content"] else txt',
    '            elif it_type == "Reasoning":',
    '                stxt = "\\n".join(it.get("summary_text") or []).strip()',
    '                if stxt:',
    '                    if cur_asst is None:',
    '                        cur_asst = {"id": f"a_{len(messages)}", "role": "assistant", "content": "", "thinking": stxt, "tools": [], "status": "done", "createdAt": ts}',
    '                    else:',
    '                        cur_asst["thinking"] = (cur_asst["thinking"] + "\\n\\n" + stxt).strip() if cur_asst["thinking"] else stxt',
    '            elif it_type == "CommandExecution":',
    '                if cur_asst is None:',
    '                    cur_asst = {"id": f"a_{len(messages)}", "role": "assistant", "content": "", "thinking": "", "tools": [], "status": "done", "createdAt": ts}',
    '                cmd_raw = it.get("command")',
    '                cmd_str = " ".join(cmd_raw) if isinstance(cmd_raw, list) else str(cmd_raw or "")',
    '                if cmd_str.startswith("/bin/bash -lc "): cmd_str = cmd_str[14:]',
    '                cur_asst["tools"].append({"id": it.get("id") or ("t_" + str(len(cur_asst["tools"]))), "name": "Shell", "title": cmd_str[:120], "input": cmd_str, "output": str(it.get("aggregated_output") or "")[:3000], "status": "error" if (it.get("exit_code") or 0) != 0 else "done"})',
    '            elif it_type == "Extension":',
    '                if cur_asst is None:',
    '                    cur_asst = {"id": f"a_{len(messages)}", "role": "assistant", "content": "", "thinking": "", "tools": [], "status": "done", "createdAt": ts}',
    '                q = it.get("query") or it.get("kind") or "Tool"',
    '                cur_asst["tools"].append({"id": it.get("id") or ("t_" + str(len(cur_asst["tools"]))), "name": it.get("kind") or "Tool", "title": str(q)[:120], "input": str(q), "output": "", "status": "done"})',
    '        elif t == "event_msg" and p.get("type") == "token_count" and cur_asst is not None:',
    '            lu = (p.get("info") or {}).get("last_token_usage")',
    '            if lu: cur_asst["usage"] = lu',
    '    flush_asst()',
    '    result["messages"] = messages[-120:]',
    'elif agent == "agy":',
    '    fp = os.path.expanduser(f"~/.gemini/antigravity-cli/brain/{sid}/.system_generated/logs/transcript.jsonl")',
    '    if not os.path.exists(fp):',
    '        print(json.dumps({"error": "未找到对应的 Antigravity 会话文件"}, ensure_ascii=False))',
    '        sys.exit(0)',
    '    meta_path = os.path.expanduser("~/.gemini/antigravity-cli/cache/conversation_metadata.json")',
    '    if os.path.exists(meta_path):',
    '        try:',
    '            meta = ((json.load(open(meta_path, encoding="utf-8")).get("conversations") or {}).get(sid) or {}).get("summary") or {}',
    '            if meta.get("Title"): result["title"] = meta["Title"]',
    '            uris = meta.get("WorkspaceURIs") or []',
    '            if uris and isinstance(uris[0], str): result["cwd"] = uris[0].replace("file://", "")',
    '        except Exception: pass',
    '    messages = []',
    '    cur_asst = None',
    '    def flush_asst():',
    '        global cur_asst',
    '        if cur_asst and (cur_asst["content"].strip() or cur_asst["tools"] or cur_asst["thinking"].strip()):',
    '            messages.append(cur_asst)',
    '        cur_asst = None',
    '    for line in open(fp, encoding="utf-8", errors="ignore"):',
    '        try: o = json.loads(line)',
    '        except Exception: continue',
    '        src = o.get("source"); typ = o.get("type")',
    '        ts = parse_ts(o.get("created_at"))',
    '        if src == "USER_EXPLICIT" and typ == "USER_INPUT":',
    '            flush_asst()',
    '            raw = o.get("content") or ""',
    '            m = re.search(r"<USER_REQUEST>\\s*(.*?)\\s*</USER_REQUEST>", raw, re.S)',
    '            txt = (m.group(1) if m else raw).strip()',
    '            if txt:',
    '                messages.append({"id": "u_" + str(o.get("step_index", len(messages))), "role": "user", "content": txt, "status": "done", "createdAt": ts})',
    '                if not result["title"]: result["title"] = txt.replace("\\n", " ")[:36]',
    '        elif src == "MODEL" and typ == "PLANNER_RESPONSE":',
    '            if o.get("model"): result["model"] = o["model"]',
    '            txt = (o.get("content") or "").strip()',
    '            thk = (o.get("thinking") or "").strip()',
    '            usage = {"input_tokens": int(o.get("input_tokens") or 0), "cache_read_tokens": int(o.get("cache_read_tokens") or 0), "output_tokens": int(o.get("output_tokens") or 0)}',
    '            if cur_asst is None:',
    '                cur_asst = {"id": "a_" + str(o.get("step_index", len(messages))), "role": "assistant", "content": txt, "thinking": thk, "tools": [], "usage": usage, "status": "done", "createdAt": ts}',
    '            else:',
    '                if thk: cur_asst["thinking"] = (cur_asst["thinking"] + "\\n\\n" + thk).strip() if cur_asst["thinking"] else thk',
    '                if txt: cur_asst["content"] = (cur_asst["content"] + "\\n\\n" + txt).strip() if cur_asst["content"] else txt',
    '                cur_asst["usage"] = usage',
    '            for tc in (o.get("tool_calls") or []):',
    '                if isinstance(tc, dict):',
    '                    cur_asst["tools"].append({"id": tc.get("id") or ("t_" + str(len(cur_asst["tools"]))), "name": tc.get("name") or "Tool", "title": str(tc.get("name") or "Tool"), "input": str(tc.get("args") or tc.get("arguments") or "")[:1500], "output": "", "status": "done"})',
    '    flush_asst()',
    '    result["messages"] = messages[-120:]',
    'print(json.dumps(result, ensure_ascii=False))'
  ].join('\n');

  const b64Py = Buffer.from(pyCode, 'utf8').toString('base64');
  const cmd = `python3 -c "$(printf '%s' '${b64Py}' | base64 -d)" '${b64Args}' 2>/dev/null`;
  const res = await execOnce(hostConfig, cmd, 15000);
  const parsed = JSON.parse((res.stdout || '').trim() || '{}');
  if (parsed.error) throw new Error(parsed.error);
  return parsed;
}
